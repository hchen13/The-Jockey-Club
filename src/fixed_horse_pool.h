inline bool Eligible(horse_attributes::Ranks raw)
{
    if (!raw.Valid()) return false;
    const int displayed_speed=horse_attributes::DisplayLevel(raw.speed);
    return displayed_speed>=5 && displayed_speed<=9;
}
template<class HashName, class ModelAvailable, class ReadRanks>
std::vector<Choice> Collect(std::span<const char* const> names, HashName hash_name,
    ModelAvailable available, ReadRanks read)
{
    std::vector<Choice> choices;
    for (const char* name:names) {
        const Hash model=hash_name(name);
        if (!model || !available(model)) continue;
        const auto ranks=read(model);
        if (Eligible(ranks)) choices.push_back({name,model,ranks});
    }
    return choices;
}
inline void AvoidPrevious(std::vector<Choice>& choices, Hash previous)
{
    if (choices.size()>1) std::erase_if(choices,[&](const Choice& c){return c.model==previous;});
}
