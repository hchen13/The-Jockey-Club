inline const Labels* Find(std::string_view model) {
    const auto it=std::find_if(std::begin(kApproved),std::end(kApproved),
        [&](const Labels& l){return model==l.model;});
    return it==std::end(kApproved)?nullptr:it;
}
inline const Labels* FindForRace(std::string_view model) {
    if(const auto* ordinary=Find(model))return ordinary;
    for(const auto& special:kRaceSpecial)if(model==special.model)return &special;
    return nullptr;
}
template<class HasLabel>
bool TextReady(const Labels& labels,HasLabel has) { return has(labels.breed) && has(labels.coat); }
