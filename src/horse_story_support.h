struct Labels { const char* model; const char* breed; const char* coat; };
// Rockstar's BREED_* labels are often the complete coat + breed name (for
// example "Dark Bay Roan Mustang"), while COAT_* is "Dark Bay Roan Coat".
// They are separate fields in the native horse card; never concatenate them
// or present the compound label as though it were only the breed.
inline std::string BreedOnlyText(std::string_view compound,std::string_view coat){
    // Some localized BREED_* strings already append " - <coat> Coat". Strip
    // that display suffix before removing the coat prefix from the breed.
    if(const auto separator=compound.find(" - ");separator!=std::string_view::npos)
        compound=compound.substr(0,separator);
    const std::string_view original=compound;
    constexpr std::string_view english_suffix=" Coat";
    constexpr std::string_view chinese_suffix="毛色";
    if(coat.ends_with(english_suffix))coat.remove_suffix(english_suffix.size());
    else if(coat.ends_with(chinese_suffix))coat.remove_suffix(chinese_suffix.size());
    if(!coat.empty() && compound.starts_with(coat)){
        compound.remove_prefix(coat.size());
        while(!compound.empty() && (compound.front()==' ' || compound.front()=='-' || compound.front()==':'))
            compound.remove_prefix(1);
    }else if(!coat.empty() && compound.ends_with(coat)){
        compound.remove_suffix(coat.size());
        while(!compound.empty() && (compound.back()==' ' || compound.back()=='-' || compound.back()==':'))
            compound.remove_suffix(1);
    }
    // Some game labels already give the entire coat+breed name in both slots.
    // Stripping such a coat would erase the only valid horse name; keep the
    // original label rather than refusing to open the native information card.
    return std::string(compound.empty()?original:compound);
}
