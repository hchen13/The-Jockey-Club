"""Bound Clubhouse-owned analysis data, without touching game progression.

Only names generated by the analysis server are eligible.  Unknown files,
reparse points and recordings still present in the game's source directory
are never automatically removed.  Call from the background worker when no
analysis job is using the affected files.
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import stat
from maintenance import delete_file, safe_path
from clubhouse_runtime import InstalledLayout
from output_policy import bounded_write

ARCHIVE_NAME = re.compile(r"^(race-\d+-\d+-\d+)\.json\.gz$")
RECORD_ID = re.compile(r"^race-\d+-\d+-\d+$")
SOURCE_NAME = re.compile(r"^(race-\d+-\d+-\d+)\.jsonl(?:\.mszip)?(?:\.part)?$")
EXPORT_NAME = re.compile(r"^[A-Za-z0-9_-]+-(?:plan|survey)\.json(?:\.tmp)?$")
COMPARISON_DIR = re.compile(r"^[0-9a-f]{64}$")
COMPARISON_NAME = re.compile(r"^(?:current|legacy|hybrid|sqp2|sqp4)\.json(?:\.tmp)?$")


def _reparse(info):
    return stat.S_ISLNK(info.st_mode) or bool(getattr(info, "st_file_attributes", 0) & 0x400)


def _directory(path):
    try:
        info = path.lstat()
        return not _reparse(info) and stat.S_ISDIR(info.st_mode)
    except OSError:
        return False


def _file(path):
    try:
        info = path.lstat()
        return info if not _reparse(info) and stat.S_ISREG(info.st_mode) else None
    except OSError:
        return None


def _inside(path, root):
    try:
        return path.resolve(strict=True).is_relative_to(root.resolve(strict=True))
    except (OSError, RuntimeError):
        return False


def _remove_verified(path, root, expected):
    # Recheck identity immediately before unlinking. Never recurse or follow a
    # junction, and never replace an unknown file on a failed cleanup.
    current = _file(path)
    if (not current or not _inside(path, root) or
        (current.st_dev, current.st_ino, current.st_size, current.st_mtime_ns) !=
            (expected.st_dev, expected.st_ino, expected.st_size, expected.st_mtime_ns)):
        return False
    try:
        delete_file(root, path, expected=expected)
        return True
    except OSError:
        return False


class StorageRetention:
    # Existing users keep their current archive (222 entries / 134 MiB as of
    # 2026-10-31); older analysis-only records roll out once these limits apply.
    ARCHIVE_FILES = 512
    ARCHIVE_BYTES = 512 * 1024 * 1024
    INDEX_BYTES = 8 * 1024 * 1024
    EXPORT_FILES = 256
    EXPORT_BYTES = 256 * 1024 * 1024
    COMPARISON_FILES = 512
    COMPARISON_BYTES = 256 * 1024 * 1024
    RECORD_BYTES = 32 * 1024 * 1024

    def publish_archive(self, identifier, payload):
        if not isinstance(identifier, str) or not RECORD_ID.fullmatch(identifier):
            raise ValueError('Invalid generated recording identifier')
        folder = self.state / 'recordings'
        bounded_write(folder, folder / (identifier + '.json.gz'), payload,
                      max_files=self.ARCHIVE_FILES, max_bytes=self.ARCHIVE_BYTES,
                      max_file_bytes=self.RECORD_BYTES, max_directories=0, max_depth=0)

    @classmethod
    def publish_export(cls, root, destination, payload):
        bounded_write(root, destination, payload, max_files=cls.EXPORT_FILES,
                      max_bytes=cls.EXPORT_BYTES, max_file_bytes=32 * 1024 * 1024,
                      max_directories=2, max_depth=1)

    @classmethod
    def publish_comparison(cls, root, destination, payload):
        bounded_write(root, destination, payload, max_files=cls.COMPARISON_FILES,
                      max_bytes=cls.COMPARISON_BYTES, max_file_bytes=32 * 1024 * 1024,
                      max_directories=cls.COMPARISON_FILES, max_depth=1)

    def check_index(self, payload):
        if len(payload) > self.INDEX_BYTES:
            raise OSError('Recording index capacity reached; existing records preserved')

    def __init__(self, game, state):
        self.game = Path(game)
        self.state = Path(state)

    def archive_present(self, identifier):
        if not isinstance(identifier, str) or not RECORD_ID.fullmatch(identifier):
            return False
        folder = self.state / "recordings"
        path = folder / (identifier + ".json.gz")
        return bool(_directory(self.state) and _directory(folder) and
                    _inside(folder, self.state) and _file(path) and _inside(path, folder))

    def _source_ids(self):
        result = set()
        folder = InstalledLayout(self.game).recordings
        if not _directory(folder):
            try:
                folder.lstat()
            except FileNotFoundError:
                return result
            except OSError:
                pass
            # A junction, inaccessible directory or unexpected file is not
            # evidence that no source recording exists.
            return None
        if not safe_path(self.game, folder):
            # The consolidated location has additional parent directories;
            # reject a junction in any of them before treating it as evidence.
            return None
        try:
            for path in folder.iterdir():
                match = SOURCE_NAME.fullmatch(path.name)
                # A matching but inaccessible or redirected entry is still a
                # reason to protect the corresponding archive from deletion.
                if match:
                    result.add(match.group(1))
        except OSError:
            # Unknown source inventory must never be interpreted as empty.
            return None
        return result

    def prune_archives(self, records, *, may_delete=lambda: True):
        """Mutate records only for verified archive files actually removed."""
        folder = self.state / "recordings"
        if not _directory(self.state) or not _directory(folder) or not _inside(folder, self.state):
            return {"removed": 0, "bytes": 0, "blocked": True}
        protected = self._source_ids()
        if protected is None:
            return {"removed": 0, "bytes": 0, "blocked": True}
        files = []
        try:
            for path in folder.iterdir():
                match = ARCHIVE_NAME.fullmatch(path.name)
                info = _file(path) if match else None
                if info:
                    files.append((info.st_mtime_ns, path.name, path, info, match.group(1)))
        except OSError:
            return {"removed": 0, "bytes": 0, "blocked": True}
        files.sort(key=lambda item: (item[0], item[1]))
        count = len(files)
        total = sum(item[3].st_size for item in files)
        # Index is strictly diagnostic metadata; the game ledger is elsewhere.
        index_size = len(json.dumps(records, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
        removed = freed = repaired = 0
        removed_ids = []
        stopped = False

        def permitted():
            try:
                return bool(may_delete())
            except Exception:
                return False

        def forget(identifier):
            nonlocal index_size
            value = records[identifier]
            # A dict's compact JSON size is the sum of its encoded entries,
            # braces and commas. Avoid serializing an 8 MiB index for each
            # deleted archive when many entries become eligible at once.
            entry_size = len(json.dumps({identifier: value}, ensure_ascii=False,
                                        separators=(",", ":")).encode("utf-8")) - 2
            index_size -= entry_size + (1 if len(records) > 1 else 0)
            del records[identifier]

        # A process interruption can leave an index entry after its archive
        # was removed. Repair only positively missing generated archives;
        # inaccessible/redirected files are not treated as absent.
        for identifier in list(records):
            if not isinstance(identifier, str) or not RECORD_ID.fullmatch(identifier) or identifier in protected:
                continue
            path = folder / (identifier + ".json.gz")
            try:
                path.lstat()
            except FileNotFoundError:
                if not permitted():
                    stopped = True
                    break
                forget(identifier)
                repaired += 1
                removed_ids.append(identifier)
            except OSError:
                pass
        for _, _, path, info, identifier in files:
            if stopped:
                break
            if count <= self.ARCHIVE_FILES and total <= self.ARCHIVE_BYTES and index_size <= self.INDEX_BYTES:
                break
            if identifier in protected:
                continue
            # Re-scan before each destructive step. A source or compression
            # stage that appeared since the first inventory protects its
            # corresponding archive. Unknown inventory is fail-closed.
            current_sources = self._source_ids()
            if current_sources is None:
                break
            if identifier in current_sources:
                continue
            if not permitted():
                stopped = True
                break
            if not _remove_verified(path, folder, info):
                continue
            count -= 1
            total -= info.st_size
            freed += info.st_size
            removed += 1
            removed_ids.append(identifier)
            if identifier in records:
                forget(identifier)
        return {"removed": removed, "bytes": freed, "repaired": repaired, "ids": removed_ids,
                "blocked": stopped or count > self.ARCHIVE_FILES or total > self.ARCHIVE_BYTES or index_size > self.INDEX_BYTES,
                "stopped": stopped}

    def prune_caches(self, *, may_delete=lambda: True):
        removed = freed = 0
        stopped = False
        for name, count_limit, byte_limit in (("exports", self.EXPORT_FILES, self.EXPORT_BYTES),
                                               ("comparisons", self.COMPARISON_FILES, self.COMPARISON_BYTES)):
            folder = self.state / name
            if not _directory(self.state) or not _directory(folder) or not _inside(folder, self.state):
                continue
            items = []
            try:
                for sub in folder.iterdir():
                    if not _directory(sub) or not _inside(sub, folder):
                        continue
                    if name == "exports" and sub.name not in ("host", "bookmaker"):
                        continue
                    if name == "comparisons" and not COMPARISON_DIR.fullmatch(sub.name):
                        continue
                    for path in sub.iterdir():
                        valid = EXPORT_NAME.fullmatch(path.name) if name == "exports" else COMPARISON_NAME.fullmatch(path.name)
                        info = _file(path) if valid else None
                        if info:
                            items.append((info.st_mtime_ns, str(path), path, info))
            except OSError:
                continue
            items.sort(key=lambda item: (item[0], item[1]))
            count, total = len(items), sum(item[3].st_size for item in items)
            for _, _, path, info in items:
                if count <= count_limit and total <= byte_limit:
                    break
                # Recheck parent too: a swapped junction must never redirect us.
                if not _directory(path.parent) or not _inside(path.parent, folder):
                    continue
                try:
                    permitted = bool(may_delete())
                except Exception:
                    permitted = False
                if not permitted:
                    stopped = True
                    break
                if _remove_verified(path, folder, info):
                    count -= 1
                    total -= info.st_size
                    removed += 1
                    freed += info.st_size
            if stopped:
                break
        return {"removed": removed, "bytes": freed, "stopped": stopped}
